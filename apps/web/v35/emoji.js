/**
 * كل الرموز لزرّ «+» في شريط التفاعل، مرتّبةً في أقسام.
 *
 * الشريط السريع يبقى ستة رموز؛ هذه للباقي. قائمة ثابتة لا مكتبة: رموز
 * Unicode الشائعة التي يرسمها أندرويد، والخادم يقبل أي رمز واحد منها.
 */

const split = (s) =>
  (typeof Intl !== 'undefined' && Intl.Segmenter
    ? [...new Intl.Segmenter('ar', { granularity: 'grapheme' }).segment(s)].map((x) => x.segment)
    : Array.from(s)
  ).filter((x) => x.trim() && !/^[\uFE0F\u200D]$/.test(x));

